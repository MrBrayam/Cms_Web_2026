<?php
/**
 * Sitemap XML output.
 *
 * @package WPInterface\SEO
 */

namespace WPInterface\SEO\Sitemaps;

use WPInterface\SEO\Support\Branding;

defined( 'ABSPATH' ) || exit;

/**
 * Renders sitemap index, URL sets and the XSL stylesheet.
 */
final class Renderer {

	/**
	 * Sitemap index.
	 *
	 * @param list<array{loc: string, lastmod?: string}> $sitemaps Sitemap files.
	 */
	public function index( array $sitemaps ): string {
		$xml = $this->header() . '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";

		foreach ( $sitemaps as $sitemap ) {
			$xml .= "\t<sitemap>\n\t\t<loc>" . esc_xml( $sitemap['loc'] ) . "</loc>\n";

			if ( ! empty( $sitemap['lastmod'] ) ) {
				$xml .= "\t\t<lastmod>" . esc_xml( $sitemap['lastmod'] ) . "</lastmod>\n";
			}

			$xml .= "\t</sitemap>\n";
		}

		return $xml . "</sitemapindex>\n";
	}

	/**
	 * URL set.
	 *
	 * @param list<array<string, mixed>> $entries Entries: loc, lastmod, images, news, videos.
	 */
	public function urlset( array $entries ): string {
		$xml = $this->header()
			. '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"'
			. ' xmlns:news="http://www.google.com/schemas/sitemap-news/0.9" xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"'
			. ' xmlns:xhtml="http://www.w3.org/1999/xhtml">' . "\n";

		foreach ( $entries as $entry ) {
			$xml .= "\t<url>\n\t\t<loc>" . esc_xml( $entry['loc'] ) . "</loc>\n";

			if ( ! empty( $entry['lastmod'] ) ) {
				$xml .= "\t\t<lastmod>" . esc_xml( $entry['lastmod'] ) . "</lastmod>\n";
			}

			// Language versions (hreflang), including the page itself.
			foreach ( $entry['alternates'] ?? array() as $alternate ) {
				$xml .= "\t\t<xhtml:link rel=\"alternate\" hreflang=\"" . esc_xml( (string) $alternate['hreflang'] ) . '" href="' . esc_xml( (string) $alternate['href'] ) . "\" />\n";
			}

			foreach ( array_slice( $entry['images'] ?? array(), 0, 1000 ) as $image ) {
				$xml .= "\t\t<image:image>\n\t\t\t<image:loc>" . esc_xml( $image ) . "</image:loc>\n\t\t</image:image>\n";
			}

			if ( ! empty( $entry['news'] ) ) {
				$news = $entry['news'];
				$xml .= "\t\t<news:news>\n\t\t\t<news:publication>\n"
					. "\t\t\t\t<news:name>" . esc_xml( (string) $news['name'] ) . "</news:name>\n"
					. "\t\t\t\t<news:language>" . esc_xml( (string) $news['language'] ) . "</news:language>\n"
					. "\t\t\t</news:publication>\n"
					. "\t\t\t<news:publication_date>" . esc_xml( (string) $news['date'] ) . "</news:publication_date>\n"
					. "\t\t\t<news:title>" . esc_xml( (string) $news['title'] ) . "</news:title>\n"
					. "\t\t</news:news>\n";
			}

			foreach ( $entry['videos'] ?? array() as $video ) {
				$xml .= "\t\t<video:video>\n"
					. "\t\t\t<video:thumbnail_loc>" . esc_xml( (string) $video['thumbnail'] ) . "</video:thumbnail_loc>\n"
					. "\t\t\t<video:title>" . esc_xml( (string) $video['title'] ) . "</video:title>\n"
					. "\t\t\t<video:description>" . esc_xml( mb_substr( (string) $video['description'], 0, 2048 ) ) . "</video:description>\n";

				if ( ! empty( $video['content_loc'] ) ) {
					$xml .= "\t\t\t<video:content_loc>" . esc_xml( (string) $video['content_loc'] ) . "</video:content_loc>\n";
				}

				if ( ! empty( $video['player_loc'] ) ) {
					$xml .= "\t\t\t<video:player_loc>" . esc_xml( (string) $video['player_loc'] ) . "</video:player_loc>\n";
				}

				if ( ! empty( $video['duration'] ) && (int) $video['duration'] <= 28800 ) {
					$xml .= "\t\t\t<video:duration>" . (int) $video['duration'] . "</video:duration>\n";
				}

				$xml .= "\t\t</video:video>\n";
			}

			$xml .= "\t</url>\n";
		}

		return $xml . "</urlset>\n";
	}

	/**
	 * XSL stylesheet that makes sitemaps readable in a browser.
	 */
	public function stylesheet(): string {
		$title = esc_xml( __( 'XML Sitemap', 'wpinterface-seo' ) );
		$intro = esc_xml(
			Branding::credit()
				/* translators: %s: plugin name. */
				? sprintf( __( 'This sitemap lists the pages search engines may index. It is generated by %s.', 'wpinterface-seo' ), Branding::name() )
				: __( 'This sitemap lists the pages search engines may index.', 'wpinterface-seo' )
		);
		$col_url     = esc_xml( __( 'URL', 'wpinterface-seo' ) );
		$col_images  = esc_xml( __( 'Images', 'wpinterface-seo' ) );
		$col_updated = esc_xml( __( 'Last modified', 'wpinterface-seo' ) );
		$col_sitemap = esc_xml( __( 'Sitemap', 'wpinterface-seo' ) );
		$count_label = esc_xml( __( 'Number of URLs:', 'wpinterface-seo' ) );

		$template = implode(
			"\n",
			array(
				'<?xml version="1.0" encoding="UTF-8"?>',
				'<xsl:stylesheet version="1.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform" xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
				'<xsl:output method="html" encoding="UTF-8" indent="yes"/>',
				'<xsl:template match="/">',
				'<html lang="en">',
				'<head>',
				'<meta charset="UTF-8"/>',
				'<meta name="robots" content="noindex, follow"/>',
				'<title>{title}</title>',
				'<link rel="stylesheet" href="{css}"/>', // phpcs:ignore WordPress.WP.EnqueuedResources.NonEnqueuedStylesheet -- XSL for the XML sitemap, not a WordPress page: wp_enqueue_style() cannot reach it.
				'</head>',
				'<body><main>',
				'<h1>{title}</h1>',
				'<p>{intro}</p>',
				'<xsl:choose>',
				'<xsl:when test="sitemap:sitemapindex">',
				'<p>{count_label} <xsl:value-of select="count(sitemap:sitemapindex/sitemap:sitemap)"/></p>',
				'<table><thead><tr><th>{col_sitemap}</th><th>{col_updated}</th></tr></thead><tbody>',
				'<xsl:for-each select="sitemap:sitemapindex/sitemap:sitemap">',
				'<tr><td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td><td class="date"><xsl:value-of select="sitemap:lastmod"/></td></tr>',
				'</xsl:for-each>',
				'</tbody></table>',
				'</xsl:when>',
				'<xsl:otherwise>',
				'<p>{count_label} <xsl:value-of select="count(sitemap:urlset/sitemap:url)"/></p>',
				'<table><thead><tr><th>{col_url}</th><th>{col_images}</th><th>{col_updated}</th></tr></thead><tbody>',
				'<xsl:for-each select="sitemap:urlset/sitemap:url">',
				'<tr><td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td><td class="num"><xsl:value-of select="count(image:image)"/></td><td class="date"><xsl:value-of select="sitemap:lastmod"/></td></tr>',
				'</xsl:for-each>',
				'</tbody></table>',
				'</xsl:otherwise>',
				'</xsl:choose>',
				'</main></body>',
				'</html>',
				'</xsl:template>',
				'</xsl:stylesheet>',
			)
		);

		return strtr(
			$template,
			array(
				'{css}'         => esc_url( add_query_arg( 'ver', WPISEO_VERSION, WPISEO_URL . 'assets/css/sitemap.css' ) ),
				'{title}'       => $title,
				'{intro}'       => $intro,
				'{col_url}'     => $col_url,
				'{col_images}'  => $col_images,
				'{col_updated}' => $col_updated,
				'{col_sitemap}' => $col_sitemap,
				'{count_label}' => $count_label,
			)
		);
	}

	/**
	 * XML declaration and stylesheet reference.
	 */
	private function header(): string {
		return '<?xml version="1.0" encoding="UTF-8"?>' . "\n"
			. '<?xml-stylesheet type="text/xsl" href="' . esc_url( Router::stylesheet_url() ) . '"?>' . "\n";
	}
}
